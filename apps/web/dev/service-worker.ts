import { createHash } from 'node:crypto'
import { readdirSync } from 'node:fs'
import { join } from 'node:path'
import type { Plugin } from 'vite'

// Emits /sw.js with an explicit precache allowlist of the public shell for this build.
export function serviceWorker(): Plugin {
  return {
    name: 'caloryst-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const icons = readdirSync(join(import.meta.dirname, '..', 'public', 'icons')).map((f) => `/icons/${f}`)
      const built = Object.keys(bundle).filter((f) => f.startsWith('assets/')).map((f) => `/${f}`)
      const precache = ['/', '/manifest.webmanifest', ...icons, ...built].sort()
      const version = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12)
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: workerSource(version, precache) })
    },
  }
}

function workerSource(version: string, precache: string[]): string {
  return `// Generated by dev/service-worker.ts. Public shell only: never caches API, session or auth data.
const PREFIX = 'caloryst-shell-'
const CACHE = PREFIX + ${JSON.stringify(version)}
const PRECACHE = ${JSON.stringify(precache)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting()
})

self.addEventListener('fetch', (event) => {
  const { request } = event
  const url = new URL(request.url)
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return
  if (request.mode === 'navigate') {
    // Only "/" is a frontend route; the shell fallback never replaces an API response.
    if (url.pathname === '/') event.respondWith(fetch(request).catch(() => caches.match('/')))
    return
  }
  if (PRECACHE.includes(url.pathname)) {
    event.respondWith(caches.match(url.pathname).then((hit) => hit || fetch(request)))
  }
})
`
}
